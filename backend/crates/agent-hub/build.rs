//! Adapter discovery at build time, the Rust form of adapters/__init__.py's `pkgutil.iter_modules`: every
//! `src/adapters/*.rs` except `mod.rs`, `base.rs` and `_*.rs` is an adapter module that must expose
//! `pub fn adapter() -> Option<Result<Arc<dyn ClientAdapter>, String>>`. Adding a client adapter is ONE new file
//! (e.g. deepseek_harness.rs); nothing else changes. Module order is sorted, like pkgutil's.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default())
        .join("src")
        .join("adapters");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut mods: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&dir) {
        for e in rd.flatten() {
            let p = e.path();
            let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
                continue;
            };
            let Some(stem) = name.strip_suffix(".rs") else { continue };
            if stem == "mod" || stem == "base" || stem.starts_with('_') {
                continue;
            }
            if !stem
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            {
                continue;
            }
            println!("cargo:rerun-if-changed={}", p.display());
            mods.push((stem.to_string(), p));
        }
    }
    mods.sort();
    let mut out = String::from("// @generated by build.rs from src/adapters/*.rs; do not edit.\n");
    for (m, p) in &mods {
        let _ = writeln!(out, "#[path = {:?}]\npub mod {m};", p.display().to_string());
    }
    out.push_str("/// (module name, its `adapter()` constructor), in pkgutil order.\n");
    out.push_str("pub(crate) const MODULES: &[(&str, Ctor)] = &[\n");
    for (m, _) in &mods {
        let _ = writeln!(out, "    ({m:?}, {m}::adapter),");
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("adapters_gen.rs");
    if let Err(e) = std::fs::write(&dest, out) {
        println!("cargo:warning=cannot write {}: {e}", dest.display());
    }
}
